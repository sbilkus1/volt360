bool calib_speed(const char *path, float bed_temp, int nozzle_temp, float layer_h,
                 float line_w, float print_speed, float travel_speed, float filament_dia,
                 float speed_min, float speed_max, float speed_step) {
    if (!path) return false;
    FILE *f = fopen(path, "w"); if (!f) return false;
    emit_header(f, bed_temp, nozzle_temp, "Speed Test");
    float e = 0, z = layer_h;
    fprintf(f, "G1 Z%.3f F%.0f\n", z, travel_speed * 60);
    float px = 50, py = 100;
    int n = (int)((speed_max - speed_min) / speed_step) + 1;
    for (int i = 0; i < n; i++) {
        float spd = speed_min + i * speed_step;
        float ly = py - i * 8;
        g92_reset(f); e = 0;
        travel(f, &e, px, ly, 0, travel_speed);
        unretract(f, &e, 0, spd);
        extruder_move(f, &e, px + 80, ly, px, ly, line_w, layer_h, filament_dia, spd, 1);
    }
    emit_footer(f, 0, travel_speed, &e); fclose(f); return true;
}
