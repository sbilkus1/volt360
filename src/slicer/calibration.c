#include "calibration.h"
#include <stdio.h>
#include <math.h>
#include <string.h>

#ifndef M_PI
#define M_PI 3.14159265358979
#endif

static void g92_reset(FILE *f) { fprintf(f, "G92 E0 ; reset extruder\n"); }

static void retract(FILE *f, float *e, float retract_mm, float travel_speed) {
    if (retract_mm > 0) { fprintf(f, "G1 E-%.3f F%.0f ; retract\n", retract_mm, travel_speed * 60); *e -= retract_mm; }
}

static void unretract(FILE *f, float *e, float retract_mm, float print_speed) {
    if (retract_mm > 0) { fprintf(f, "G1 E+%.3f F%.0f ; unretract\n", retract_mm, print_speed * 60); *e += retract_mm; }
}

static float vol_cross(float filament_dia) {
    return (float)(M_PI * (filament_dia / 2.0) * (filament_dia / 2.0));
}

static void extruder_move(FILE *f, float *e, float x, float y, float ex, float ey,
                          float line_w, float layer_h, float filament_dia, float speed, int first) {
    float L = sqrtf((x - ex) * (x - ex) + (y - ey) * (y - ey));
    float vol = L * line_w * layer_h;
    float de = vol / vol_cross(filament_dia);
    *e += de;
    if (first) fprintf(f, "G1 X%.3f Y%.3f E%.4f F%.0f\n", x, y, *e, speed * 60);
    else fprintf(f, "G1 X%.3f Y%.3f E%.4f\n", x, y, *e);
}

static void travel(FILE *f, float *e, float x, float y, float retract_mm, float travel_speed) {
    retract(f, e, retract_mm, travel_speed);
    fprintf(f, "G0 X%.3f Y%.3f F%.0f ; travel\n", x, y, travel_speed * 60);
}

static void emit_header(FILE *f, float bed_temp, int nozzle_temp, const char *type) {
    fprintf(f, "; Calibration: %s (generated by Volt360)\n", type);
    fprintf(f, "M140 S%d\nM190 S%d\n", (int)bed_temp, (int)bed_temp);
    fprintf(f, "M104 S%d\nM109 S%d\n", nozzle_temp, nozzle_temp);
    fprintf(f, "G28 ; home\n");
}

static void emit_footer(FILE *f, float retract_mm, float travel_speed, float *e) {
    retract(f, e, retract_mm, travel_speed);
    fprintf(f, "M104 S0 ; hotend off\nM140 S0 ; bed off\nG0 X0 Y200 F%.0f ; present\nM84 ; motors off\n", travel_speed * 60);
}

// ================= temperature tower =================
bool calib_temp_tower(const char *path, float bed_temp, int temp_min, int temp_max, int temp_step,
                      float layer_h, float line_w, float print_speed, float travel_speed,
                      float retract_mm, float filament_dia) {
    if (!path || temp_step <= 0 || temp_max <= temp_min) return false;
    FILE *f = fopen(path, "w");
    if (!f) return false;
    emit_header(f, bed_temp, temp_min, "Temperature Tower");
    float e = 0;
    float sx = 100, sy = 100; // tower center
    float hw = 10, hd = 10; // tower half-size
    float z = layer_h;
    int num_levels = (temp_max - temp_min) / temp_step + 1;
    float level_height = 10; // mm per temp level
    int layers_per_level = (int)(level_height / layer_h + 0.5f);
    if (layers_per_level < 1) layers_per_level = 1;

    for (int lvl = 0; lvl < num_levels; lvl++) {
        int t = temp_min + lvl * temp_step;
        if (lvl > 0) { fprintf(f, "M104 S%d\nM109 S%d\n", t, t); }
        for (int li = 0; li < layers_per_level; li++) {
            fprintf(f, "; temp=%d layer=%d\n", t, li);
            fprintf(f, "G1 Z%.3f F%.0f\n", z, travel_speed * 60);
            g92_reset(f); e = 0;
            travel(f, &e, sx - hw, sy - hd, retract_mm, travel_speed);
            unretract(f, &e, retract_mm, print_speed);
            // perimeters
            for (int wall = 0; wall < 2; wall++) {
                float cx = sx - hw + wall * line_w, cy = sy - hd + wall * line_w;
                float cw = hw * 2 - wall * line_w * 2, cd = hd * 2 - wall * line_w * 2;
                if (cw <= 0 || cd <= 0) break;
                extruder_move(f, &e, cx, cy, cx, cy, line_w, layer_h, filament_dia, print_speed, 1);
                extruder_move(f, &e, cx + cw, cy, cx, cy, line_w, layer_h, filament_dia, print_speed, 0);
                extruder_move(f, &e, cx + cw, cy + cd, cx + cw, cy, line_w, layer_h, filament_dia, print_speed, 0);
                extruder_move(f, &e, cx, cy + cd, cx + cw, cy + cd, line_w, layer_h, filament_dia, print_speed, 0);
                extruder_move(f, &e, cx, cy, cx, cy + cd, line_w, layer_h, filament_dia, print_speed, 0);
            }
            z += layer_h;
        }
    }
    emit_footer(f, retract_mm, travel_speed, &e);
    fclose(f);
    return true;
}

// ================= flow rate =================
bool calib_flow_rate(const char *path, float bed_temp, int nozzle_temp, float layer_h,
                     float line_w, float print_speed, float travel_speed, float retract_mm,
                     float filament_dia, float mult_min, float mult_max, float mult_step) {
    if (!path || mult_step <= 0 || mult_max <= mult_min) return false;
    FILE *f = fopen(path, "w");
    if (!f) return false;
    emit_header(f, bed_temp, nozzle_temp, "Flow Rate Calibration");
    float e = 0, z = layer_h;
    float sx = 50, sy = 100, sq = 20; // square size
    float cx = sx, cy = sy;
    int num = (int)((mult_max - mult_min) / mult_step) + 1;

    fprintf(f, "G1 Z%.3f F%.0f\n", z, travel_speed * 60);

    for (int i = 0; i < num; i++) {
        float mult = mult_min + i * mult_step;
        float mw = line_w * mult;
        float px = cx + (float)(i % 3) * (sq + 10);
        float py = cy - (float)(i / 3) * (sq + 10);
        fprintf(f, "; square %d flow=%.0f%%\n", i, mult * 100);
        g92_reset(f); e = 0;
        travel(f, &e, px, py, retract_mm, travel_speed);
        unretract(f, &e, retract_mm, print_speed);
        // single line outline (solid infill for top surface)
        extruder_move(f, &e, px, py, px, py, mw, layer_h, filament_dia, print_speed, 1);
        extruder_move(f, &e, px + sq, py, px, py, mw, layer_h, filament_dia, print_speed, 0);
        extruder_move(f, &e, px + sq, py + sq, px + sq, py, mw, layer_h, filament_dia, print_speed, 0);
        extruder_move(f, &e, px, py + sq, px + sq, py + sq, mw, layer_h, filament_dia, print_speed, 0);
        extruder_move(f, &e, px, py, px, py + sq, mw, layer_h, filament_dia, print_speed, 0);
        // infill
        float step = mw * 0.95f;
        for (float yy = py + step; yy < py + sq; yy += step) {
            extruder_move(f, &e, px, yy, px + sq, yy, mw, layer_h, filament_dia, print_speed, 0);
        }
    }
    emit_footer(f, retract_mm, travel_speed, &e);
    fclose(f);
    return true;
}

// ================= pressure advance =================
bool calib_pressure_advance(const char *path, float bed_temp, int nozzle_temp, float layer_h,
                            float line_w, float print_speed, float travel_speed, float retract_mm,
                            float filament_dia, float pa_min, float pa_max, float pa_step,
                            bool klipper) {
    if (!path || pa_step <= 0 || pa_max <= pa_min) return false;
    FILE *f = fopen(path, "w");
    if (!f) return false;
    emit_header(f, bed_temp, nozzle_temp, "Pressure Advance Pattern");
    float e = 0, z = layer_h;
    fprintf(f, "G1 Z%.3f F%.0f\n", z, travel_speed * 60);
    float px = 50, py = 150;
    int num = (int)((pa_max - pa_min) / pa_step) + 1;

    for (int i = 0; i < num; i++) {
        float pa = pa_min + i * pa_step;
        float lx = px, ly = py - i * 12;
        int l = 80; // line length
        if (klipper)
            fprintf(f, "SET_PRESSURE_ADVANCE ADVANCE=%.4f\n", pa);
        else
            fprintf(f, "M900 K%.2f\n", pa);
        fprintf(f, "; PA=%.4f\n", pa);
        g92_reset(f); e = 0;
        travel(f, &e, lx, ly, retract_mm, travel_speed);
        unretract(f, &e, retract_mm, print_speed);
        // fast line (test corner sharpness at speed)
        extruder_move(f, &e, lx + l, ly, lx, ly, line_w, layer_h, filament_dia, print_speed, 1);
        // slow line (reference)
        extruder_move(f, &e, lx, ly + 2, lx + l, ly + 2, line_w, layer_h, filament_dia, print_speed * 0.5f, 0);
    }
    emit_footer(f, retract_mm, travel_speed, &e);
    fclose(f);
    return true;
}

